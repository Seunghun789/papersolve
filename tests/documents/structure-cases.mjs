export async function structureCases({db,as,denied,check}) {
 const scalar=async(sql,args=[]) => (await db.query(sql,args)).rows[0];
 const source=async()=> (await scalar("insert into source_inputs(tenant_id,channel,name) values(1,'사진','structure fixture') returning id")).id;
 const propose=async(kind,payload,sid)=> (await scalar('insert into proposals(tenant_id,kind,payload,source_input_id) values(1,$1,$2,$3) returning id',[kind,payload,sid])).id;
 const preview=async(id,n=1)=> (await as(n,'select passo_structure_preview(1,$1) as p',[id]))[0].p;
 const answer=async(id,action,rev,n=1)=>as(n,'select * from passo_answer_structure(1,$1,$2,$3)',[id,rev??(await preview(id)).revision,action]);
 const prop={label:'수 량',name:'수량',dtype:'number',unit:'개',is_entity:false};
 const sid=await source();
 const cell={version:'cell-state-v1',raw:'-',value:null,status:'explicit_dash'};
 const r=await scalar("insert into records(tenant_id,type_name,occurred_at,data,status,source_input_id) values(1,'구조 검증','2026-11-14',$1,'대기',$2) returning *",[{'수 량':cell},sid]);
 const q=await propose('종류',{type:'구조 검증',props:[prop]},sid);
 const snapshot=await preview(q);
 check('structure preview includes exact raw cell and impact',snapshot.records[0].data['수 량'].status==='explicit_dash'&&snapshot.affected_count===1);
 await denied('foreign structure preview denied',()=>preview(q,2));
 check('viewer may inspect structure',(await preview(q,3)).revision===snapshot.revision);
 await denied('viewer cannot accept structure',()=>answer(q,'accept',snapshot.revision,3));
 await denied('uploader cannot accept structure',()=>answer(q,'accept',snapshot.revision,5));
 await denied('foreign structure write denied',()=>answer(q,'accept',snapshot.revision,2));
 await denied('structure stale revision denied',()=>answer(q,'accept','0'.repeat(32)));
 await answer(q,'accept',snapshot.revision);
 const accepted=await scalar('select * from proposals where id=$1',[q]);
 check('structure decision records actor and answer',accepted.decided_by===1&&accepted.status==='승인'&&accepted.payload.answer==='accept');
 const after=await scalar('select * from records where id=$1',[r.id]);
 check('type accept settles waiting record without changing cells',after.status==='확정'&&JSON.stringify(after.data)===JSON.stringify(r.data));
 check('type accept creates property and both aliases',(await scalar("select count(*)::int n from alias_dict where type_name='구조 검증' and prop_name='수량'")).n===2);
 await denied('duplicate structure decision conflicts',()=>answer(q,'accept',snapshot.revision));

 const stale=await propose('칸',{type:'구조 검증',...prop,name:'메모',label:'메모',dtype:'text',unit:null},sid);
 const staleView=await preview(stale);
 await db.query("update records set uncertain='[\"수 량\"]' where id=$1",[r.id]);
 await denied('record uncertainty change invalidates preview',()=>answer(stale,'accept',staleView.revision));
 const v2=await preview(stale);
 await db.exec("update property_defs set unit='상자' where type_name='구조 검증'");
 await denied('property change invalidates preview',()=>answer(stale,'accept',v2.revision));
 await answer(stale,'accept');
 check('add column does not fill historical blanks',!(await scalar('select data from records where id=$1',[r.id])).data['메모']);
 const rejected=await propose('칸',{type:'구조 검증',label:'무시',name:'무시',dtype:'text'},sid);
 await answer(rejected,'reject');
 check('reject column stores ignored alias and keeps raw',(await scalar("select prop_name from alias_dict where type_name='구조 검증' and alias='무시'")).prop_name===null);
 const same=await propose('같은 칸',{type:'구조 검증',label:'개수',similar_to:'수량',dtype:'number',unit:'개'},sid);
 await answer(same,'accept');
 check('same column maps to existing property',(await scalar("select prop_name from alias_dict where type_name='구조 검증' and alias='개수'")).prop_name==='수량');
 const different=await propose('같은 칸',{type:'구조 검증',label:'다른 수',similar_to:'수량',dtype:'number',unit:'개'},sid);
 await answer(different,'reject');
 check('different column creates separate definition',(await scalar("select prop_name from alias_dict where type_name='구조 검증' and alias='다른 수'")).prop_name==='다른 수');
 const homonym=await propose('같은 칸',{type:'구조 검증',label:'수량',similar_to:'수량',dtype:'number',unit:'개'},sid);
 await answer(homonym,'reject');
 check('same spelling can be explicitly separated',(await scalar("select prop_name from alias_dict where type_name='구조 검증' and alias='수량'")).prop_name==='수량 (2)');
 const invalid=await propose('같은 칸',{type:'구조 검증',label:'없는 대상',similar_to:'없음',dtype:'number'},sid);
 await denied('same column cannot reference nonexistent property',()=>answer(invalid,'accept'));
 const conflict=await propose('칸',{type:'구조 검증',...prop,unit:'원'},sid);
 await denied('existing property cannot be silently overwritten',()=>answer(conflict,'accept'));
 check('failed decision rolls back proposal',(await scalar('select status from proposals where id=$1',[conflict])).status==='대기');

 const sid2=await source();
 const split=await propose('종류',{type:'나눠 확인',props:[{...prop,unit:null},{label:'메모',name:'메모',dtype:'text'}]},sid2);
 await db.query("insert into records(tenant_id,type_name,occurred_at,data,status,source_input_id) values(1,'나눠 확인','2026-11-14',$1,'대기',$2)",[{'수 량':cell,메모:''},sid2]);
 await answer(split,'split');
 const children=(await db.query("select * from proposals where source_input_id=$1 and kind='칸' order by id",[sid2])).rows;
 check('split creates one pending review per column',children.length===2&&children.every(q=>q.status==='대기'));
 check('split keeps records waiting',(await scalar('select status from records where source_input_id=$1',[sid2])).status==='대기');
 await answer(children[0].id,'accept');
 check('partial column review keeps records waiting',(await scalar('select status from records where source_input_id=$1',[sid2])).status==='대기');
 await answer(children[1].id,'reject');
 check('last structural review settles source',(await scalar('select status from records where source_input_id=$1',[sid2])).status==='확정');
 const sid3=await source();
 const no=await propose('종류',{type:'거절 종류',props:[prop]},sid3);
 await db.query("insert into records(tenant_id,type_name,occurred_at,data,status,source_input_id) values(1,'거절 종류','2026-11-14',$1,'대기',$2)",[{'수 량':cell},sid3]);
 await answer(no,'reject');
 check('reject new type rejects waiting rows without deleting originals',(await scalar('select status,data from records where source_input_id=$1',[sid3])).status==='거절');

 const bad=await propose('종류',{type:'rollback',props:[prop,{label:'bad',name:'bad',dtype:'invalid'}]},null);
 await denied('split rejects malformed property without children',()=>answer(bad,'split'));
 await denied('invalid later property rolls back entire type',()=>answer(bad,'accept'));
 check('failed type leaves no partial definition',(await scalar("select count(*)::int n from object_types where name='rollback'")).n===0);
 const collisions=await propose('종류',{type:'collisions',props:[prop,{...prop,name:'other'}]},null);
 await denied('one label cannot silently target two columns',()=>answer(collisions,'accept'));
 const followup=await propose('종류',{type:'후속',props:[{label:'설비',name:'설비',dtype:'text',ref_class:'설비'},{label:'위치',name:'위치',dtype:'text'}],links:[{from:'설비',to:'위치',kind:'연결',reason:'표의 관계'}]},null);
 await answer(followup,'accept');
 check('structure keeps entity classification as pending',(await scalar("select count(*)::int n from proposals where kind='대상 분류' and payload->>'type'='후속' and status='대기'")).n===1);
 check('structure keeps relation as pending',(await scalar("select count(*)::int n from proposals where kind='연결' and payload->>'from'='후속.설비' and status='대기'")).n===1);
 await denied('private structure helpers inaccessible',()=>as(1,"select passo_private.structure_alias(1,'구조 검증','attack','수량')"));
 await denied('anonymous cannot inspect structure',()=>as(1,'select passo_structure_preview(1,$1)',[invalid],'anon'));
}
