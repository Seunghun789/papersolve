export async function policyCases({db,as,denied,check}) {
 const insert=async(table,fields,values)=>(await db.query(`insert into ${table}(${fields}) values(${values.map((_,i)=>'$'+(i+1)).join(',')}) returning *`,values)).rows[0];
 const source=await insert('source_inputs','tenant_id,channel,name,auto',[1,'사진','policy test',true]);
 const sid=source.id;
 await db.exec("insert into object_types(tenant_id,name,kind) values(1,'정책 기록','기록'); insert into property_defs(tenant_id,type_name,name,dtype,unit) values(1,'정책 기록','수량','number','개'),(1,'정책 기록','비고','text',null)");
 const cell={version:'cell-state-v1',raw:'-',value:null,status:'explicit_dash'};
 const rec=await insert('records','tenant_id,type_name,occurred_at,data,status,source_input_id,uncertain',[1,'정책 기록','2026-11-14',{'수량':cell,'비고':'메모'},'확정',sid,['비고']]);
 const preview=async(n=1)=>(await as(n,'select public.passo_source_preview(1,$1) as p',[sid]))[0].p;
 const reopen=async(rev,n=1)=>as(n,'select public.passo_reopen_source(1,$1,$2) as p',[sid,rev]);
 let snap=await preview();
 await denied('viewer cannot reopen source',()=>reopen(snap.revision,3));
 await denied('foreign reader cannot inspect source preview',()=>preview(2));
 await db.query('update records set uncertain=$1 where id=$2',[[],rec.id]);
 await denied('source CAS includes uncertainty',()=>reopen(snap.revision));
 snap=await preview(); const opened=(await reopen(snap.revision))[0].p.review_id;
 check('reopen preserves raw state and excludes records from totals',(await preview()).records[0].data['수량'].status==='explicit_dash'&&(await preview()).records[0].status==='대기');
 await denied('duplicate reopen rejected',()=>reopen(snap.revision));
 const policy=async()=> (await as(1,'select public.passo_policy_preview(1,$1) as p',[sid]))[0].p;
 check('reopened read is never automatic',!(await policy()).items.find(q=>q.id===opened).decision.eligible);
 const read=async(revision,answer='accept',n=1)=>as(n,'select public.passo_answer_read(1,$1,$2,$3)',[opened,revision,answer]);
 await denied('viewer cannot confirm read',async()=>read((await preview()).revision,'accept',3));
 await read((await preview()).revision);
 check('read review republishes exact records',(await preview()).records[0].status==='확정');
 const audit=async()=>(await db.query('select * from passo_audit where tenant_id=1 and reversible order by id desc limit 1')).rows[0];
 const undo=async(id,n=1)=>as(n,'select public.passo_undo(1,$1)',[id]);
 let a=await audit();
 await denied('viewer cannot undo',()=>undo(a.id,3));
 await denied('foreign tenant cannot undo',()=>undo(a.id,2));
 await undo(a.id);
 check('undo read restores waiting status',(await preview()).records[0].status==='대기');
 check('undo review reopens with manual marker',(await policy()).items.find(q=>q.id===opened).decision.reason.includes('다시'));
 await denied('double undo rejected',()=>undo(a.id));
 await read((await preview()).revision);
 const edit=async(expected,value)=>as(1,'select * from public.passo_edit_cells(1,$1,$2,$3)',[rec.id,expected,{'수량':value}]);
 let r=(await preview()).records[0]; await edit(r.data,0); a=await audit();
 check('cell edit has complete audited old/new values',a.before_state.records[0].data['수량'].status==='explicit_dash'&&a.after_state.records[0].data['수량'].value===0);
 await undo(a.id); check('undo restores dash not numeric zero',(await preview()).records[0].data['수량'].status==='explicit_dash');
 r=(await preview()).records[0];await edit(r.data,10);a=await audit();r=(await preview()).records[0];await edit(r.data,11);
 await denied('later edits block earlier undo',()=>undo(a.id));
 await denied('direct audit tampering denied',()=>as(1,'update passo_audit set reversible=true'));
 await denied('anonymous cannot read audit',()=>as(1,'select * from passo_audit',[],'anon'));
 check('audit table applies tenant RLS',(await as(2,'select * from passo_audit where tenant_id=1')).length===0);
 const propose=async(kind,p,e={})=>insert('proposals','tenant_id,kind,payload,evidence,source_input_id',[1,kind,p,e,sid]);
 const decision=async(q)=>(await policy()).items.find(x=>x.id===q.id).decision;
 const same=await propose('같은 칸',{type:'정책 기록',label:'갯수',similar_to:'수량',dtype:'number',unit:'상자'});
 check('unit mismatch held for human',!(await decision(same)).eligible);
 const different=await propose('같은 칸',{type:'정책 기록',label:'수량글',similar_to:'수량',dtype:'text'});
 check('dtype mismatch becomes distinct column',(await decision(different)).action==='reject');
 for(let i=0;i<3;i++)await insert('records','tenant_id,type_name,occurred_at,data,status,source_input_id',[1,'정책 기록','2026-11-14',{'수량':10},'확정',sid]);
 const scale=await propose('같은 칸',{type:'정책 기록',label:'수량10배',similar_to:'수량',dtype:'number',unit:'개'},{samples:[100,110,120]});
 check('tenfold magnitude held for human',!(await decision(scale)).eligible);
 const text=await propose('애매한 값',{type:'정책 기록',label:'비고',value:'메모',record_id:rec.id});
 check('ambiguous nonnumeric text keeps unconfirmed',(await decision(text)).action==='unconfirmed');
 const numeric=await propose('애매한 값',{type:'정책 기록',label:'수량',value:11,record_id:rec.id});
 check('numeric ambiguity stays pending',!(await decision(numeric)).eligible);
 for(const reason of ['missing','unknown','unreadable']){
  const q=await propose('애매한 값',{type:'정책 기록',label:'비고',value:'?',record_id:rec.id},{reason});
  check(reason+' never quietly accepted',!(await decision(q)).eligible);
 }
 const manual=await propose('칸',{type:'정책 기록',label:'직접',name:'직접',dtype:'text'},{user:true});
 check('user proposals never automatic',!(await decision(manual)).eligible);
 const missingLink=await propose('연결',{from:'정책 기록.비고',to:'정책 기록.없는칸',kind:'연결'});
 check('unsupported link evidence stays pending',!(await decision(missingLink)).eligible);
 const p=await policy();
 await denied('viewer cannot apply policy',()=>as(3,'select public.passo_apply_policy(1,$1,$2)',[sid,p.revision]));
 await denied('stale policy preview denied',()=>as(1,'select public.passo_apply_policy(1,$1,$2)',[sid,'0'.repeat(32)]));
 await as(1,'select public.passo_apply_policy(1,$1,$2)',[sid,p.revision]);
 const saved=(await db.query('select * from proposals where id=$1',[text.id])).rows[0];
 check('quiet text has policy reason and preserves uncertainty',saved.status==='승인'&&saved.payload.unconfirmed&&saved.payload.policy.version==='auto-v1');
 check('different dtype creates separate property',(await db.query("select * from property_defs where tenant_id=1 and type_name='정책 기록' and name='수량글'")).rows.length===1);
 await db.query("update source_inputs set auto=true,created_at=now()-interval '8 days' where id=$1",[sid]);
 check('seven day reopen window enforced',!(await preview()).can_reopen);
 await denied('expired reopen rejected server-side',async()=>reopen((await preview()).revision));
 for(const call of ["select passo_private.auto_apply(1,1)","select passo_private.apply_structure(1,1,'','accept')","select passo_private.edit_cells_v1(1,1,'{}','{}')"]){await denied('private mutation helper denied '+call,()=>as(1,call));}
 await db.query('delete from source_inputs where id=$1',[sid]);
 await db.exec("delete from property_defs where type_name='정책 기록';delete from alias_dict where type_name='정책 기록';delete from object_types where name='정책 기록';");
}
